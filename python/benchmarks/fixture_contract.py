from __future__ import annotations

import hashlib
import os
import stat
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import polars as pl

FIXTURE_MANIFEST_PROTOCOL = "openwrangler-installed-performance-fixtures-v1"


@dataclass(frozen=True, slots=True)
class FixtureSpec:
    kind: Literal["csv", "parquet"]
    rows: int
    columns: int

    @property
    def names(self) -> list[str]:
        return [f"c{column:02d}" for column in range(self.columns)]

    @property
    def sentinel_rows(self) -> tuple[int, ...]:
        return tuple(sorted({0, self.rows // 2, self.rows - 1}))


def fixture_specs(smoke: bool) -> dict[str, FixtureSpec]:
    return {
        "csv": FixtureSpec("csv", 2_000 if smoke else 100_000, 8 if smoke else 50),
        "parquet": FixtureSpec("parquet", 5_000 if smoke else 1_000_000, 8 if smoke else 20),
    }


def create_fixtures(directory: Path, smoke: bool = False) -> dict[str, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    _assert_owned_directory(directory)
    fixtures: dict[str, Path] = {}
    for kind, spec in fixture_specs(smoke).items():
        path = directory / f"{spec.rows}-{spec.columns}.{kind}"
        _ensure_fixture(path, spec)
        fixtures[kind] = path
    return fixtures


def fixture_manifest(directory: Path, smoke: bool = False) -> dict[str, object]:
    fixtures = create_fixtures(directory, smoke)
    specs = fixture_specs(smoke)
    entries: dict[str, object] = {}
    for kind, path in fixtures.items():
        spec = specs[kind]
        metadata = path.stat()
        entries[kind] = {
            "fileName": path.name,
            "format": kind,
            "rows": spec.rows,
            "columns": spec.columns,
            "columnType": "Int64",
            "columnNamePattern": "c followed by a zero-padded zero-based integer",
            "sentinelRows": list(spec.sentinel_rows),
            "sha256": _sha256(path),
            "bytes": metadata.st_size,
        }
    return {
        "protocol": FIXTURE_MANIFEST_PROTOCOL,
        "smoke": smoke,
        "generator": {
            "contractVersion": 1,
            "implementation": "polars",
            "implementationVersion": pl.__version__,
        },
        "license": "CC0-1.0",
        "redistribution": "Deterministic synthetic integer fixtures generated by Open Wrangler.",
        "fixtures": entries,
    }


def assert_fixture_contract(path: Path, spec: FixtureSpec) -> None:
    _assert_owned_regular_file(path)
    frame = pl.scan_csv(path) if spec.kind == "csv" else pl.scan_parquet(path)
    schema = frame.collect_schema()
    if schema.names() != spec.names:
        raise AssertionError(f"Fixture {path.name} has unexpected columns: {schema.names()!r}.")
    wrong_types = {
        name: str(dtype) for name, dtype in zip(schema.names(), schema.dtypes(), strict=True) if dtype != pl.Int64
    }
    if wrong_types:
        raise AssertionError(f"Fixture {path.name} has non-Int64 columns: {wrong_types!r}.")
    row_count = int(frame.select(pl.len()).collect(engine="streaming").item())
    if row_count != spec.rows:
        raise AssertionError(f"Fixture {path.name} has {row_count} rows; expected {spec.rows}.")

    row_number = "__openwrangler_fixture_row"
    indexed = frame.with_row_index(row_number)
    invalid_counts = indexed.select(
        [
            pl.col(name).ne_missing(pl.col(row_number).cast(pl.Int64) + column).cast(pl.UInt64).sum().alias(name)
            for column, name in enumerate(spec.names)
        ]
    ).collect(engine="streaming")
    incorrect = {name: int(count) for name, count in zip(spec.names, invalid_counts.row(0), strict=True) if count != 0}
    if incorrect:
        raise AssertionError(f"Fixture {path.name} has invalid value counts by column: {incorrect!r}.")


def _ensure_fixture(path: Path, spec: FixtureSpec) -> None:
    try:
        metadata = path.lstat()
    except FileNotFoundError:
        metadata = None
    if metadata is not None:
        if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
            raise AssertionError(f"Fixture target {path.name} must be a single-link regular file.")
        try:
            assert_fixture_contract(path, spec)
            return
        except Exception:
            # A stale partial fixture must never make benchmark numbers look
            # valid. Regenerate and validate a replacement before publishing it.
            pass

    with tempfile.NamedTemporaryFile(
        mode="wb",
        prefix=f".{path.name}.",
        suffix=path.suffix,
        dir=path.parent,
        delete=False,
    ) as temporary_file:
        temporary = Path(temporary_file.name)
    try:
        _write_fixture(temporary, spec)
        assert_fixture_contract(temporary, spec)
        if path.exists() or path.is_symlink():
            current = path.lstat()
            if stat.S_ISLNK(current.st_mode) or not stat.S_ISREG(current.st_mode) or current.st_nlink != 1:
                raise AssertionError(f"Fixture target {path.name} changed to an unsafe file.")
        os.replace(temporary, path)
        _assert_owned_regular_file(path)
    finally:
        temporary.unlink(missing_ok=True)


def _write_fixture(path: Path, spec: FixtureSpec) -> None:
    if spec.kind == "csv":
        pl.DataFrame(
            {name: pl.int_range(column, spec.rows + column, eager=True) for column, name in enumerate(spec.names)}
        ).write_csv(path)
        return
    (
        pl.LazyFrame()
        .select(pl.int_range(0, spec.rows).alias("c00"))
        .with_columns([(pl.col("c00") + column).alias(name) for column, name in enumerate(spec.names[1:], start=1)])
        .sink_parquet(path)
    )


def _assert_owned_directory(directory: Path) -> None:
    metadata = directory.lstat()
    if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISDIR(metadata.st_mode):
        raise AssertionError("The performance fixture root must be a real directory.")


def _assert_owned_regular_file(path: Path) -> None:
    metadata = path.lstat()
    if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
        raise AssertionError(f"Fixture {path.name} must remain a single-link regular file.")


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()
