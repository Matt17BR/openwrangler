import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import prettier from "prettier";
import { canonicalOperationCatalog } from "./operation-catalog.mjs";

const root = resolve(import.meta.dirname, "..");
const packageJson = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const schema = JSON.parse(readFileSync(resolve(root, "protocol", "openwrangler.v2.schema.json"), "utf8"));
const outputPath = resolve(root, "docs", "reference.md");
const operations = canonicalOperationCatalog(schema);

const output = await prettier.format(
  `${[
    "# Generated interface reference",
    "",
    "> Generated from `package.json` and `protocol/openwrangler.v2.schema.json`. Do not edit this file by hand; run `npm run generate:reference`.",
    "",
    "## Commands",
    "",
    table(
      ["Command", "Title"],
      packageJson.contributes.commands.map((command) => [code(command.command), escapeCell(command.title)])
    ),
    "",
    "## Keyboard shortcuts",
    "",
    table(
      ["Command", "Windows / Linux", "macOS", "Context"],
      packageJson.contributes.keybindings.map((binding) => [
        code(binding.command),
        code(binding.key),
        code(binding.mac ?? binding.key),
        code(binding.when)
      ])
    ),
    "",
    "## Settings",
    "",
    table(
      ["Setting", "Type", "Default", "Allowed values", "Description"],
      Object.entries(packageJson.contributes.configuration.properties).map(([name, setting]) => [
        code(name),
        code(Array.isArray(setting.type) ? setting.type.join(" | ") : setting.type),
        code(JSON.stringify(setting.default)),
        setting.enum ? setting.enum.map((value) => code(JSON.stringify(value))).join(", ") : "None",
        escapeCell(setting.description)
      ])
    ),
    "",
    "## Transformation operations",
    "",
    table(
      ["Kind", "Title", "Group", "Required parameters", "Optional parameters"],
      operations.map((operation) => [
        code(operation.kind),
        escapeCell(operation.title),
        escapeCell(operation.group),
        parameterList(operation.required),
        parameterList(operation.optional)
      ])
    ),
    "",
    "## Runtime protocol v2",
    "",
    `Canonical schema: \`protocol/openwrangler.v2.schema.json\`. Protocol version: \`${schema.definitions.ProtocolVersion.enum.join(", ")}\`.`,
    "",
    table(
      ["Direction", "Schema type", "Message kind"],
      [
        ...messageKinds("OpenWranglerRequest").map(({ name, kind }) => ["Request", code(name), code(kind)]),
        ...messageKinds("OpenWranglerResponse").map(({ name, kind }) => ["Response", code(name), code(kind)])
      ]
    ),
    "",
    "## Notebook MIME types",
    "",
    ...notebookMimeTypeRows(packageJson.contributes.notebookRenderer),
    ""
  ].join("\n")}\n`,
  { parser: "markdown" }
);

if (process.argv.includes("--check")) {
  const existing = readFileSync(outputPath, "utf8");
  if (existing !== output) {
    throw new Error("Generated interface reference is stale. Run npm run generate:reference.");
  }
} else {
  writeFileSync(outputPath, output, "utf8");
}

function messageKinds(unionName) {
  return schema.definitions[unionName].oneOf.map((entry) => {
    const name = entry.$ref.split("/").at(-1);
    const definition = schema.definitions[name];
    const object = definition.allOf?.find((part) => part.properties?.kind) ?? definition;
    return { name, kind: object.properties.kind.const };
  });
}

function notebookMimeTypeRows(renderers) {
  if (!Array.isArray(renderers)) throw new Error("Notebook renderer contributions must be an array.");
  return renderers.flatMap((renderer) => {
    if (!renderer || typeof renderer !== "object" || Array.isArray(renderer)) {
      throw new Error("Notebook renderer contributions must be objects.");
    }
    if (Array.isArray(renderer.mimeTypes)) {
      if (
        typeof renderer.entrypoint !== "string" ||
        renderer.mimeTypes.length === 0 ||
        renderer.mimeTypes.some((mimeType) => typeof mimeType !== "string" || mimeType.length === 0)
      ) {
        throw new Error("Direct notebook renderer contributions must declare an entrypoint and MIME types.");
      }
      return renderer.mimeTypes.map((mimeType) => `- \`${mimeType}\``);
    }
    const entrypoint = renderer.entrypoint;
    if (
      !Object.hasOwn(renderer, "mimeTypes") &&
      entrypoint &&
      typeof entrypoint === "object" &&
      !Array.isArray(entrypoint) &&
      Object.keys(entrypoint).length === 2 &&
      entrypoint.extends === "vscode.builtin-renderer" &&
      entrypoint.path === "./media/notebookRenderer.js"
    ) {
      return [];
    }
    throw new Error("Notebook renderer contributions must be direct renderers or the validated renderer extension.");
  });
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`)
  ].join("\n");
}

function parameterList(parameters) {
  return parameters.length ? parameters.map(code).join(", ") : "None";
}

function code(value) {
  return `\`${String(value).replaceAll("`", "\\`")}\``;
}

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}
