import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import prettier from "prettier";
import { canonicalOperationCatalog } from "./operation-catalog.mjs";

const root = resolve(import.meta.dirname, "..");
const outputPath = resolve(root, "docs", "reference.md");
const canonicalMimeRenderer = {
  id: "openWrangler.renderer",
  displayName: "Open Wrangler Renderer",
  entrypoint: "./media/notebookRenderer.js",
  requiresMessaging: "optional",
  mimeTypes: ["application/vnd.openwrangler.viewer.v2+json"]
};
const canonicalHtmlExtension = {
  id: "openWrangler.inlineHtmlUpgrade",
  displayName: "Open Wrangler Inline HTML Upgrade",
  entrypoint: {
    extends: "vscode.builtin-renderer",
    path: "./media/notebookRenderer.js"
  },
  requiresMessaging: "always"
};

export async function runReferenceGenerator({ check }) {
  const output = await generateReference();
  if (check) {
    const existing = readFileSync(outputPath, "utf8");
    if (existing !== output) {
      throw new Error("Generated interface reference is stale. Run npm run generate:reference.");
    }
    return;
  }
  writeFileSync(outputPath, output, "utf8");
}

async function generateReference() {
  const packageJson = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
  const schema = JSON.parse(readFileSync(resolve(root, "protocol", "openwrangler.v2.schema.json"), "utf8"));
  const operations = canonicalOperationCatalog(schema);
  return prettier.format(
    `${[
      "# Generated interface reference",
      "",
      "> Generated from `package.json` and `protocol/openwrangler.v2.schema.json`. Do not edit this file by hand; run `npm run generate:reference`.",
      "",
      "## Commands",
      "",
      table(
        ["Command", "Title"],
        packageJson.contributes.commands.map((command) => [code(command.command), escapeCell(command.title)])
      ),
      "",
      "## Keyboard shortcuts",
      "",
      table(
        ["Command", "Windows / Linux", "macOS", "Context"],
        packageJson.contributes.keybindings.map((binding) => [
          code(binding.command),
          code(binding.key),
          code(binding.mac ?? binding.key),
          code(binding.when)
        ])
      ),
      "",
      "## Settings",
      "",
      table(
        ["Setting", "Type", "Default", "Allowed values", "Description"],
        Object.entries(packageJson.contributes.configuration.properties).map(([name, setting]) => [
          code(name),
          code(Array.isArray(setting.type) ? setting.type.join(" | ") : setting.type),
          code(JSON.stringify(setting.default)),
          setting.enum ? setting.enum.map((value) => code(JSON.stringify(value))).join(", ") : "None",
          escapeCell(setting.description)
        ])
      ),
      "",
      "## Transformation operations",
      "",
      table(
        ["Kind", "Title", "Group", "Required parameters", "Optional parameters"],
        operations.map((operation) => [
          code(operation.kind),
          escapeCell(operation.title),
          escapeCell(operation.group),
          parameterList(operation.required),
          parameterList(operation.optional)
        ])
      ),
      "",
      "## Runtime protocol v2",
      "",
      `Canonical schema: \`protocol/openwrangler.v2.schema.json\`. Protocol version: \`${schema.definitions.ProtocolVersion.enum.join(", ")}\`.`,
      "",
      table(
        ["Direction", "Schema type", "Message kind"],
        [
          ...messageKinds(schema, "OpenWranglerRequest").map(({ name, kind }) => ["Request", code(name), code(kind)]),
          ...messageKinds(schema, "OpenWranglerResponse").map(({ name, kind }) => ["Response", code(name), code(kind)])
        ]
      ),
      "",
      "## Notebook MIME types",
      "",
      ...notebookMimeTypeRows(packageJson.contributes.notebookRenderer),
      ""
    ].join("\n")}\n`,
    { parser: "markdown" }
  );
}

function messageKinds(schema, unionName) {
  return schema.definitions[unionName].oneOf.map((entry) => {
    const name = entry.$ref.split("/").at(-1);
    const definition = schema.definitions[name];
    const object = definition.allOf?.find((part) => part.properties?.kind) ?? definition;
    return { name, kind: object.properties.kind.const };
  });
}

export function notebookMimeTypeRows(renderers) {
  if (!Array.isArray(renderers)) throw new Error("Notebook renderer contributions must be an array.");
  const mimeRenderers = renderers.filter((renderer) => matchesExactJsonShape(renderer, canonicalMimeRenderer));
  const htmlExtensions = renderers.filter((renderer) => matchesExactJsonShape(renderer, canonicalHtmlExtension));
  if (renderers.length !== 2 || mimeRenderers.length !== 1 || htmlExtensions.length !== 1) {
    throw new Error(
      "Notebook renderer contributions must contain exactly the canonical MIME-v2 renderer and built-in HTML extension."
    );
  }
  return canonicalMimeRenderer.mimeTypes.map((mimeType) => `- \`${mimeType}\``);
}

function matchesExactJsonShape(actual, expected) {
  if (Array.isArray(expected)) {
    return (
      Array.isArray(actual) &&
      actual.length === expected.length &&
      expected.every((value, index) => matchesExactJsonShape(actual[index], value))
    );
  }
  if (expected !== null && typeof expected === "object") {
    if (actual === null || typeof actual !== "object" || Array.isArray(actual)) return false;
    const expectedKeys = Object.keys(expected);
    const actualKeys = Object.keys(actual);
    return (
      actualKeys.length === expectedKeys.length &&
      expectedKeys.every((key) => Object.hasOwn(actual, key) && matchesExactJsonShape(actual[key], expected[key]))
    );
  }
  return Object.is(actual, expected);
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`)
  ].join("\n");
}

function parameterList(parameters) {
  return parameters.length ? parameters.map(code).join(", ") : "None";
}

function code(value) {
  return `\`${String(value).replaceAll("`", "\\`")}\``;
}

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}
